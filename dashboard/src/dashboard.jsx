function useBrainLayout(graph) {
  return useMemo(() => {
    const nodes = graph.nodes.filter((n) => n.soma[0] !== null)
    const count = nodes.length
    const positions = new Float32Array(count * 3)
    const baseColors = new Float32Array(count * 3)
    const idIndex = new Map()

    let cx = 0, cy = 0, cz = 0
    for (const n of nodes) { cx += n.soma[0]; cy += n.soma[1]; cz += n.soma[2] }
    cx /= count; cy /= count; cz /= count

    nodes.forEach((n, i) => {
      positions[i * 3 + 0] = (n.soma[0] - cx) * BRAIN_SCALE
      positions[i * 3 + 1] = -(n.soma[2] - cz) * BRAIN_SCALE
      positions[i * 3 + 2] = (n.soma[1] - cy) * BRAIN_SCALE
      const c = n.is_dn ? DN_COLOR
        : n.class === 'Kenyon_Cell' ? KC_COLOR
        : n.class === 'MBON' ? MBON_COLOR
        : n.class === 'DAN' ? DAN_COLOR
        : NEURON_COLOR
      baseColors[i * 3 + 0] = c.r
      baseColors[i * 3 + 1] = c.g
      baseColors[i * 3 + 2] = c.b
      idIndex.set(n.id, i)
    })
    return { positions, baseColors, idIndex, count }
  }, [graph])
}

const _obj3d = new THREE.Object3D()
const _tmpColor = new THREE.Color()

function BrainInstances({ layout, spikeQueueRef, plasticWeightRef }) {
  const meshRef = useRef()
  const { positions, baseColors, idIndex, count } = layout

  useEffect(() => {
    const mesh = meshRef.current
    if (!mesh) return
    for (let i = 0; i < count; i++) {
      _obj3d.position.set(positions[i * 3], positions[i * 3 + 1], positions[i * 3 + 2])
      _obj3d.updateMatrix()
      mesh.setMatrixAt(i, _obj3d.matrix)
      _tmpColor.setRGB(baseColors[i * 3], baseColors[i * 3 + 1], baseColors[i * 3 + 2])
      mesh.setColorAt(i, _tmpColor)
    }
    mesh.instanceMatrix.needsUpdate = true
    if (mesh.instanceColor) mesh.instanceColor.needsUpdate = true
  }, [positions, baseColors, count])

  useFrame(() => {
    const mesh = meshRef.current
    if (!mesh || !mesh.instanceColor) return
    const colors = mesh.instanceColor.array
    for (let i = 0; i < count; i++) {
      const b = i * 3
      colors[b + 0] = baseColors[b + 0] + (colors[b + 0] - baseColors[b + 0]) * COLOR_DECAY
      colors[b + 1] = baseColors[b + 1] + (colors[b + 1] - baseColors[b + 1]) * COLOR_DECAY
      colors[b + 2] = baseColors[b + 2] + (colors[b + 2] - baseColors[b + 2]) * COLOR_DECAY
    }
    const spiking = spikeQueueRef.current
    if (spiking && spiking.length) {
      for (const bodyId of spiking) {
        const idx = idIndex.get(bodyId)
        if (idx === undefined) continue
        const b = idx * 3
        colors[b + 0] = SPIKE_COLOR.r; colors[b + 1] = SPIKE_COLOR.g; colors[b + 2] = SPIKE_COLOR.b
      }
      spikeQueueRef.current = null
    }
    // Reuses this exact same per-instance color-write mechanism (not a
    // separate rendering path) to show learning: KC/MBON somas whose
    // outgoing/incoming plastic synapses have measurably moved since
    // startup get pulled toward LEARN_COLOR, proportional to how much.
    const weights = plasticWeightRef && plasticWeightRef.current
    if (weights) {
      for (const key in weights) {
        const idx = idIndex.get(Number(key))
        if (idx === undefined) continue
        const amount = Math.min(1, weights[key] * 2) // |Δw/w0| of ~0.5 -> fully saturated
        if (amount <= 0.02) continue
        const b = idx * 3
        colors[b + 0] = colors[b + 0] + (LEARN_COLOR.r - colors[b + 0]) * amount
        colors[b + 1] = colors[b + 1] + (LEARN_COLOR.g - colors[b + 1]) * amount
        colors[b + 2] = colors[b + 2] + (LEARN_COLOR.b - colors[b + 2]) * amount
      }
    }
    mesh.instanceColor.needsUpdate = true
  })

  return (
    <instancedMesh ref={meshRef} args={[null, null, count]}>
      <icosahedronGeometry args={[0.06, 1]} />
      <meshBasicMaterial vertexColors toneMapped={false} transparent opacity={0.85} />
    </instancedMesh>
  )
}

