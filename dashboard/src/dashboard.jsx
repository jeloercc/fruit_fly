// Module 5: RL "brain money" metrics — cumulative reward (integral of the
// signed PAM-minus-PPL dopamine EMA) and instantaneous MBON dopamine
// release, both already computed server-side (reward_signal /
// cumulative_reward). Drawn on a raw canvas, pushed directly from the
// WebSocket handler — no chart library, no React state.
// ---------------------------------------------------------------------

const RLMetrics = forwardRef(function RLMetrics(_props, ref) {
  const canvasRef = useRef()
  const containerRef = useRef()
  const bufRef = useRef({ dopamine: [], cumulative: [], max: 256 })

  useEffect(() => {
    const canvas = canvasRef.current
    const container = containerRef.current
    if (!canvas || !container) return
    const resize = () => {
      canvas.width = container.clientWidth
      canvas.height = container.clientHeight
      redraw()
    }
    const redraw = () => {
      const ctx = canvas.getContext('2d')
      const { width: w, height: h } = canvas
      ctx.fillStyle = '#050505'
      ctx.fillRect(0, 0, w, h)

      // Learning maturity: fraction of recent cumulative_reward deltas
      // that were non-negative — "stabilizing" read as "mostly not
      // dropping lately," directly off the same buffer already kept for
      // the chart below, not a separate tracked quantity.
      const barH = 16
      const maturity = computeMaturity(bufRef.current.cumulative)
      ctx.fillStyle = '#161616'
      ctx.fillRect(0, 0, w, barH)
      ctx.fillStyle = '#22e07a'
      ctx.fillRect(0, 0, w * (maturity / 100), barH)
      ctx.fillStyle = '#e0e0e0'
      ctx.font = '10px monospace'
      ctx.fillText(`learning maturity: ${maturity}%`, 8, barH - 5)

      const chartTop = barH
      const chartH = h - barH
      const halfH = chartTop + chartH / 2
      drawSeries(ctx, bufRef.current.dopamine, chartTop, chartH / 2 - 10, w, '#ffcc33', true, 'MBON dopamine release')
      drawSeries(ctx, bufRef.current.cumulative, halfH + 10, chartH / 2 - 10, w, '#4fa3ff', false, 'cumulative reward')
      ctx.strokeStyle = '#1a1a1a'
      ctx.beginPath(); ctx.moveTo(0, halfH); ctx.lineTo(w, halfH); ctx.stroke()
    }
    resize()
    const ro = new ResizeObserver(resize)
    ro.observe(container)
    canvas._redraw = redraw
    return () => ro.disconnect()
  }, [])

  useImperativeHandle(ref, () => ({
    pushSample(dopamine, cumulative) {
      const b = bufRef.current
      b.dopamine.push(dopamine); if (b.dopamine.length > b.max) b.dopamine.shift()
      b.cumulative.push(cumulative); if (b.cumulative.length > b.max) b.cumulative.shift()
      if (canvasRef.current && canvasRef.current._redraw) canvasRef.current._redraw()
    },
  }), [])

  return (
    <div ref={containerRef} className="module-canvas-wrap">
      <canvas ref={canvasRef} />
    </div>
  )
})

function computeMaturity(cumulative) {
  const k = Math.min(60, cumulative.length - 1)
  if (k < 5) return 0
  let nonNeg = 0
  for (let i = cumulative.length - k; i < cumulative.length; i++) {
    if (cumulative[i] - cumulative[i - 1] >= 0) nonNeg++
  }
  return Math.round((nonNeg / k) * 100)
}

function drawSeries(ctx, data, top, height, width, colorHex, zeroCentered, label) {
  ctx.fillStyle = '#7a8494'
  ctx.font = '11px monospace'
  ctx.fillText(label, 8, top + 14)
  if (data.length < 2) return
  let lo = Math.min(...data), hi = Math.max(...data)
  if (zeroCentered) { const m = Math.max(Math.abs(lo), Math.abs(hi), 1e-6); lo = -m; hi = m }
  if (hi - lo < 1e-9) { hi = lo + 1 }
  const stepX = width / (data.length - 1)
  ctx.strokeStyle = colorHex
  ctx.lineWidth = 1.5
  ctx.beginPath()
  data.forEach((v, i) => {
    const x = i * stepX
    const y = top + height - ((v - lo) / (hi - lo)) * height
    if (i === 0) ctx.moveTo(x, y); else ctx.lineTo(x, y)
  })
  ctx.stroke()
  const last = data[data.length - 1]
  ctx.fillStyle = colorHex
  ctx.font = '11px monospace'
  ctx.fillText(last.toFixed(3), width - 60, top + 14)
}

