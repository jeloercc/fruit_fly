const DN_COLOR = new THREE.Color('#ff6644')
const NEURON_COLOR = new THREE.Color('#4fa3ff')
const SPIKE_COLOR = new THREE.Color('#ffffff')
// Mushroom-body learning circuit — real neuPrint `class` populations, not
// superclass (no kenyon_cell/mushroom_body superclass exists in this
// dataset — see AGENTS.md).
const KC_COLOR = new THREE.Color('#7a5fd6')
const MBON_COLOR = new THREE.Color('#d65fb0')
const DAN_COLOR = new THREE.Color('#ffcc33')
const LEARN_COLOR = new THREE.Color('#ff2fd0')
const COLOR_DECAY = 0.85
const BRAIN_SCALE = 1 / 4000

// ---------------------------------------------------------------------
// Module 2: connectome morphology (unchanged from the pure-sandbox build —
// already matches the emissive-neon-on-black spec: neon blue central
