function ControlPanel({ graph, sendCmd, paused, sensoryDrive, noiseStd, connected, learningEnabled }) {
  const [localDrive, setLocalDrive] = useState(1.0)
  const [localNoise, setLocalNoise] = useState(0.0)

  useEffect(() => { if (sensoryDrive !== null) setLocalDrive(sensoryDrive) }, [sensoryDrive])
  useEffect(() => { if (noiseStd !== null) setLocalNoise(noiseStd) }, [noiseStd])

  const dnLeftIds = useMemo(() => graph.nodes.filter((n) => n.is_dn && n.soma_side === 'L').map((n) => n.id), [graph])
  const dnRightIds = useMemo(() => graph.nodes.filter((n) => n.is_dn && n.soma_side === 'R').map((n) => n.id), [graph])
  const sensoryIds = useMemo(() => graph.nodes.filter((n) => (n.superclass || '').includes('sensory')).map((n) => n.id), [graph])
  const pplIds = useMemo(() => graph.nodes.filter((n) => n.class === 'DAN' && (n.type || '').startsWith('PPL')).map((n) => n.id), [graph])
  const pamIds = useMemo(() => graph.nodes.filter((n) => n.class === 'DAN' && (n.type || '').startsWith('PAM')).map((n) => n.id), [graph])

  const sample = (ids, n) => {
    if (ids.length <= n) return ids
    const out = []; const used = new Set()
    while (out.length < n) {
      const i = Math.floor(Math.random() * ids.length)
      if (used.has(i)) continue
      used.add(i); out.push(ids[i])
    }
    return out
  }

  return (
    <div className="control-panel panel">
      <div className="title">brain controls</div>
      <div className="control-row">
        <button className={connected ? 'btn ok' : 'btn bad'} disabled>
          {connected ? '● connected' : '○ disconnected'}
        </button>
      </div>
      <div className="control-row buttons">
        <button className="btn primary" onClick={() => sendCmd({ cmd: paused ? 'resume' : 'pause' })}>
          {paused ? '▶ resume' : '⏸ pause'}
        </button>
        <button className="btn" onClick={() => sendCmd({ cmd: 'reset' })}>⟲ reset flight</button>
      </div>
      <label className="slider-label">
        sensory drive: {localDrive.toFixed(2)}
        <input type="range" min="0" max="3" step="0.05" value={localDrive}
          onChange={(e) => { const v = parseFloat(e.target.value); setLocalDrive(v); sendCmd({ cmd: 'set_params', sensory_drive: v }) }} />
      </label>
      <label className="slider-label">
        noise σ: {localNoise.toFixed(2)}
        <input type="range" min="0" max="1.5" step="0.02" value={localNoise}
          onChange={(e) => { const v = parseFloat(e.target.value); setLocalNoise(v); sendCmd({ cmd: 'set_params', noise_std: v }) }} />
      </label>
      <div className="title" style={{ marginTop: 10 }}>manual spike injection</div>
      <div className="control-row buttons">
        <button className="btn" onClick={() => sendCmd({ cmd: 'inject_spike', body_ids: sample(sensoryIds, 80) })}>stimulate sensory</button>
      </div>
      <div className="control-row buttons">
        <button className="btn dn-left" onClick={() => sendCmd({ cmd: 'inject_spike', body_ids: sample(dnLeftIds, 40) })}>fire DN · L</button>
        <button className="btn dn-right" onClick={() => sendCmd({ cmd: 'inject_spike', body_ids: sample(dnRightIds, 40) })}>fire DN · R</button>
      </div>

      <div className="title" style={{ marginTop: 10 }}>mushroom-body learning (KC→MBON)</div>
      <div className="control-row buttons">
        <button
          className={learningEnabled ? 'btn ok' : 'btn'}
          onClick={() => sendCmd({ cmd: 'set_learning', enabled: !learningEnabled })}
        >
          {learningEnabled ? '● learning ON — click to freeze' : '○ learning off — click to enable'}
        </button>
      </div>
      <div className="control-row buttons">
        <button className="btn dn-left" onClick={() => sendCmd({ cmd: 'inject_spike', body_ids: pplIds })}>
          fire PPL (aversive)
        </button>
        <button className="btn dn-right" onClick={() => sendCmd({ cmd: 'inject_spike', body_ids: sample(pamIds, 60) })}>
          fire PAM (appetitive)
        </button>
      </div>
    </div>
  )
}

function Minimap({ trailRef }) {
  const canvasRef = useRef()
  useEffect(() => {
    let raf
    const draw = () => {
      const canvas = canvasRef.current
      if (canvas) {
        const ctx = canvas.getContext('2d')
        const w = canvas.width, h = canvas.height
        ctx.fillStyle = 'rgba(5,7,12,0.35)'
        ctx.fillRect(0, 0, w, h)
        const trail = trailRef.current
        if (trail.length > 1) {
          // Fly-centered, not world-origin-centered — same class of bug as
          // the static tree patch (see Park/ParkChunks above and the
          // AGENTS.md entry): drawing at `w/2 + x*3` put the trail off the
          // 150x150 canvas entirely once the fly was more than ~25 world
          // units from the origin, which after any real flight duration it
          // always is. Anchor on the fly's own current position instead.
          const [fx, fz] = trail[trail.length - 1]
          ctx.strokeStyle = '#4fa3ff'; ctx.lineWidth = 1.5
          ctx.beginPath()
          trail.forEach(([x, z], i) => {
            const px = w / 2 + (x - fx) * 3, py = h / 2 - (z - fz) * 3
            if (i === 0) ctx.moveTo(px, py); else ctx.lineTo(px, py)
          })
          ctx.stroke()
          ctx.fillStyle = '#ff6644'
          ctx.beginPath(); ctx.arc(w / 2, h / 2, 3.5, 0, 2 * Math.PI); ctx.fill()
        }
      }
      raf = requestAnimationFrame(draw)
    }
    raf = requestAnimationFrame(draw)
    return () => cancelAnimationFrame(raf)
  }, [trailRef])
  return <canvas ref={canvasRef} width={150} height={150} className="minimap" />
}

