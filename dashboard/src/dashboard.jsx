function DriveBar({ label, value, range = [-0.5, 1.5] }) {
  const [lo, hi] = range
  const pct = Math.max(0, Math.min(100, ((value - lo) / (hi - lo)) * 100))
  return (
    <div className="drive-bar">
      <span>{label}</span>
      <div className="drive-bar-track"><div className="drive-bar-fill" style={{ width: `${pct}%` }} /></div>
      <span>{value.toFixed(2)}</span>
    </div>
  )
}
