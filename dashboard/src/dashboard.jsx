// Module 4: High-performance raster plot — raw <canvas>, no SVG/charting
// lib. A curated row set (DN L/R, optic L/R, KC, MBON, PAM, PPL) is built
// once from the graph; Dashboard calls ref.pushTick(spikingIds) directly
// from the WebSocket handler at broadcast rate (60Hz), which scrolls the
// canvas one column and stamps tick marks — no React re-render involved.
// ---------------------------------------------------------------------

const RASTER_ROW_SPECS = [
  { label: 'DN·L', color: '#ff6644', match: (n) => n.is_dn && n.soma_side === 'L', n: 14 },
  { label: 'DN·R', color: '#ff6644', match: (n) => n.is_dn && n.soma_side === 'R', n: 14 },
  // Eye side from `instance`, not soma_side — these two rows were
  // sampling from just 23 L / 13 R annotated neurons instead of the real
  // 2,349 / 3,749 (see the SENSORY_CHANNELS note).
  { label: 'optic·L', color: '#4fd0ff', match: (n) => n.superclass === 'ol_sensory' && (n.instance || '').endsWith('_L'), n: 10 },
  { label: 'optic·R', color: '#4fd0ff', match: (n) => n.superclass === 'ol_sensory' && (n.instance || '').endsWith('_R'), n: 10 },
  // The two exogenously-stimulated afferent populations get their own
  // rows so injected current is directly observable as localized firing
  // in the stimulated neuropil, rather than only inferable downstream.
  { label: 'ORN', color: '#22e07a', match: (n) => (n.type || '').startsWith('ORN'), n: 10 },
  { label: 'JO', color: '#22c2e0', match: (n) => (n.type || '').startsWith('JO'), n: 8 },
  { label: 'KC', color: '#7a5fd6', match: (n) => n.class === 'Kenyon_Cell', n: 10 },
  { label: 'MBON', color: '#d65fb0', match: (n) => n.class === 'MBON', n: 10 },
  { label: 'PAM', color: '#ffcc33', match: (n) => n.class === 'DAN' && (n.type || '').startsWith('PAM'), n: 6 },
  { label: 'PPL', color: '#ffcc33', match: (n) => n.class === 'DAN' && (n.type || '').startsWith('PPL'), n: 6 },
]

function useRasterRows(graph) {
  return useMemo(() => {
    const rows = []
    const idToRow = new Map()
    for (const spec of RASTER_ROW_SPECS) {
      const ids = graph.nodes.filter(spec.match).map((n) => n.id)
      const sample = ids.length > spec.n ? samplePlain(ids, spec.n) : ids
      const startRow = rows.length
      for (const id of sample) { idToRow.set(id, rows.length); rows.push({ color: spec.color }) }
      rows.push({ divider: true, label: spec.label, startRow })
    }
    return { rows, idToRow }
  }, [graph])
}

const RasterPlot = forwardRef(function RasterPlot({ rasterRows }, ref) {
  const canvasRef = useRef()
  const containerRef = useRef()
  const stateRef = useRef({ ctx: null, w: 0, h: 0, rowH: 0, col: 0 })

  useEffect(() => {
    const canvas = canvasRef.current
    const container = containerRef.current
    if (!canvas || !container) return
    const resize = () => {
      canvas.width = container.clientWidth
      canvas.height = container.clientHeight
      const ctx = canvas.getContext('2d')
      ctx.fillStyle = '#050505'
      ctx.fillRect(0, 0, canvas.width, canvas.height)
      const nRows = Math.max(1, rasterRows.rows.filter((r) => !r.divider).length)
      stateRef.current = { ctx, w: canvas.width, h: canvas.height, rowH: canvas.height / nRows, col: 0 }
    }
    resize()
    const ro = new ResizeObserver(resize)
    ro.observe(container)
    return () => ro.disconnect()
  }, [rasterRows])

  useImperativeHandle(ref, () => ({
    pushTick(spikingIds) {
      const s = stateRef.current
      if (!s.ctx) return
      const { ctx, w, h, rowH } = s
      // scroll one column left, then clear the freed rightmost column
      ctx.drawImage(canvasRef.current, 1, 0, w - 1, h, 0, 0, w - 1, h)
      ctx.fillStyle = '#050505'
      ctx.fillRect(w - 1, 0, 1, h)
      if (spikingIds && spikingIds.length) {
        for (const id of spikingIds) {
          const row = rasterRows.idToRow.get(id)
          if (row === undefined) continue
          const rowInfo = rasterRows.rows[row]
          ctx.fillStyle = rowInfo.color
          ctx.fillRect(w - 1, Math.floor(row * rowH), 1, Math.max(1, Math.ceil(rowH)))
        }
      }
    },
  }), [rasterRows])

  return (
    <div ref={containerRef} className="module-canvas-wrap">
      <canvas ref={canvasRef} />
    </div>
  )
})

