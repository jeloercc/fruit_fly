//
// Five-module grid: (1) Optic Flow Tunnel — a procedural closed-loop VR
// environment the connectome actually flies through, (2) real connectome
// morphology (navis skeleton fibers + soma instances), (3) a 2D ommatidia
// sensory matrix, (4) a raw-canvas spike raster, (5) RL "brain money"
// metrics (dopamine release / cumulative reward).
//
// Closed loop: tunnel wall proximity (Module 1) is piped straight into the
// backend's existing set_visual_input() pathway (the same one that already
// drives ol_sensory neurons), collisions/sustained clean flight fire the
// same real PPL/PAM DAN populations the manual "mushroom-body learning"
// panel already uses, and DN spike rates already broadcast as
// (thrust, yaw_rate) drive the tunnel camera. None of that required backend
// changes — telemetry_server.py / run_simulation.py already exposed every
// hook this needs (visual_input, set_group_drive, inject_spike, the
// per-tick thrust/yaw_rate/reward_signal/cumulative_reward broadcast).
//
// Perf rule: high-frequency (60Hz) telemetry never touches React state.
// WebSocket messages write into refs and mutate the DOM/canvas/Three.js
// objects directly; React state is reserved for things that actually
// change rarely (connection status, pause, learning toggle, slider seeds).

